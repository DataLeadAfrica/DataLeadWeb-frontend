export default async function handler(request) {
  const url = new URL(request.url);
  const number = (url.searchParams.get("number") || "").trim();

  // request.url does not reliably carry the address the visitor actually
  // used, so build it from the headers Vercel sets instead.
  const proto = request.headers.get("x-forwarded-proto") || "https";
  const host =
    request.headers.get("x-forwarded-host") ||
    request.headers.get("host") ||
    url.host;
  const origin = `${proto}://${host}`;

  const fonts = [
    { name: "Poppins", data: fontBytes(POPPINS_REGULAR_B64), weight: 400, style: "normal" },
    { name: "Poppins Bold", data: fontBytes(POPPINS_BOLD_B64), weight: 700, style: "normal" },
  ];

  let row = null;
  try {
    row = await lookup(number);
  } catch {
    row = null;
  }

  const ok = row && row.found && !row.revoked;
  const name = ok ? row.full_name || "" : "Data-Lead Africa";
  const programme = ok
    ? (row.is_module && row.module_title
        ? row.module_title
        : row.programme_title) || ""
    : "Certificate verification";
  const dateText = ok && row.completed_on
    ? `Completed ${prettyDate(row.completed_on)}`
    : "";
  let plateUrl = null;
  if (ok) {
    const small = plateFor(row);
    plateUrl = await loadPlate(`${origin}${small}`);
    // Fall back to the full size artwork if the small one is not deployed.
    if (!plateUrl) {
      plateUrl = await loadPlate(`${origin}${small.replace("-card.jpg", ".jpg")}`);
    }
  }

  try {
    return new ImageResponse(
      card({
        eyebrow: ok ? "VERIFIED CERTIFICATE" : "CERTIFICATE CHECK",
        name,
        programme,
        dateText,
        number: number || "",
        plateUrl,
      }),
      {
        width: 1200,
        height: 630,
        fonts,
        headers: {
          "Cache-Control": "public, max-age=3600, s-maxage=86400",
        },
      },
    );
  } catch {
    // A broken picture is worse than a plain one, so never throw.
    return new ImageResponse(
      card({
        eyebrow: "CERTIFICATE CHECK",
        name: "Data-Lead Africa",
        programme: "Certificate verification",
        dateText: "",
        number: number || "",
        plateUrl: null,
      }),
      { width: 1200, height: 630, fonts },
    );
  }
}
